import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicPath = path.join(root, 'public');
const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml' };
const assets = {};

async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) await collect(absolute);
    else {
      const key = '/' + path.relative(publicPath, absolute).split(path.sep).join('/');
      assets[key] = { type: types[path.extname(entry.name)] || 'application/octet-stream', data: (await readFile(absolute)).toString('base64') };
    }
  }
}

await collect(publicPath);
const handler = (await readFile(path.join(root, 'src/worker.js'), 'utf8')).replace('export default {', 'const handler = {');
const bundle = `// Generated by scripts/build.mjs. Edit public/ and src/, then rebuild.\n${handler}\nconst bundledAssets = ${JSON.stringify(assets)};\nexport default {\n  fetch(request, env = {}) {\n    const ASSETS = {\n      async fetch(assetRequest) {\n        const url = new URL(assetRequest.url);\n        const key = url.pathname === '/' ? '/index.html' : url.pathname;\n        const asset = bundledAssets[key];\n        if (!asset) return new Response('Not found', { status: 404 });\n        const binary = atob(asset.data);\n        const bytes = Uint8Array.from(binary, char => char.charCodeAt(0));\n        return new Response(assetRequest.method === 'HEAD' ? null : bytes, {\n          headers: { 'Content-Type': asset.type }\n        });\n      }\n    };\n    return handler.fetch(request, { ...env, ASSETS });\n  }\n};\n`;
await writeFile(path.join(root, 'worker.js'), bundle);
console.log(`Built single-file worker.js (${Object.keys(assets).length} embedded assets, ${Buffer.byteLength(bundle)} bytes).`);
